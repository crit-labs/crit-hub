"""Generate browse/, the GPU -> model -> checkpoint -> engines index, from every engine's engine.json.

Models and checkpoints are Hugging Face's: a model is the root of a pinned checkpoint's lineage, such
as Qwen/Qwen3.8-27B, and its checkpoints are the pinned repositories that derive from it, such as
unsloth/Qwen3.8-27B-NVFP4. browse/README.md lists the GPUs, browse/<gpu>/README.md the models with
engines on that GPU, browse/<gpu>/<model>/README.md that model's checkpoints with how each derives
from it, and browse/<gpu>/<model>/<checkpoint>/README.md every engine that runs that checkpoint:
measured on it, or listed in a supports group and not measured yet. browse/index.json carries each engine's card,
pinned source and pairs for the website and coding agents. Each pair keeps the model id
(qwen3.8-27b@NVFP4) and adds it split into model_name and quant, and the lab and bits Hugging Face
gives its checkpoint (below). When git history is available the
engine's dates as YYYY-MM-DD: "added", the commit that added its engine.json, and "updated", the
last commit that changed its folder (today while it has uncommitted changes); null without history,
as in a shallow clone. --check fails when browse/ is out of date instead of writing it; it ignores
the dates, which depend on the clone and on when a change is merged.

Each pinned checkpoint's place in Hugging Face's model tree (tools/hf.py) is kept in browse/hf.json,
keyed by repository@revision, and copied into its pairs as "hf": the root model and its lab, the
lineage with each step's relation, the publisher, quantization, size, license and gating. Only
--refresh reads Hugging Face, for pinned checkpoints the cache does not hold yet; to read one
again, delete its entry and refresh. Checks and builds read the cache alone.
"""
import argparse
import json
import posixpath
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hf  # noqa: E402

CACHE = "browse/hf.json"
HEADER = "<!-- Generated by tools/build_index.py from engines/*/*/engine.json; do not edit. -->\n\n"
NOTE = ("**Measured** figures are the headline numbers of the engine README's Measured section, on this GPU "
        "and checkpoint; **Measured with** says how. Figures from the same crit Eval protocol are comparable; "
        "any other method is the contributor's own report. **Supported** means the engine says it runs this "
        "pair and nobody has measured it here yet. Engines are listed, not ranked.")


def figure(value, unit):
    if value is None:
        return "–"
    if isinstance(value, list):
        return f"{value[0]:,}–{value[1]:,} {unit}"
    return f"{value:,} {unit}"


def ttft(value):
    if value is None:
        return "–"
    low, high = value if isinstance(value, list) else (value, value)
    if high < 1000:
        return figure(value, "ms")
    return figure([low / 1000, high / 1000] if low != high else low / 1000, "s")


def git(hub, *args):
    try:
        return subprocess.run(["git", "-C", str(hub), *args], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def dates(hub, folder):
    """When an engine was added and last updated, from git; None for both without full history."""
    if git(hub, "rev-parse", "--is-shallow-repository") != "false":
        return None, None
    path = folder.relative_to(hub).as_posix()
    today = date.today().isoformat()
    added = git(hub, "log", "--follow", "--diff-filter=A", "--format=%ad", "--date=short", "--", f"{path}/engine.json")
    updated = git(hub, "log", "-1", "--format=%ad", "--date=short", "--", path)
    if git(hub, "status", "--porcelain", "--", path):
        updated = today
    return (added.splitlines()[-1] if added else today), updated or today


def load_engines(hub):
    def model(name):
        base, encoding = name.split("@")
        return {"model": name, "model_name": base, "quant": encoding}

    engines = []
    for folder in sorted(p for p in (hub / "engines").glob("*/*") if p.is_dir()):
        engine = json.loads((folder / "engine.json").read_text(encoding="utf-8"))
        measured = {(r["gpu"], r["model"]): r for r in engine["results"]}
        supported = sorted({(g, m) for group in engine.get("supports", []) for g in group["gpus"]
                            for m in group["models"]} - set(measured))
        checkpoints = {m: {k: c[k] for k in ("repository", "revision")} for m, c in engine["checkpoints"].items()}
        added, updated = dates(hub, folder)
        engines.append({
            "path": folder.relative_to(hub).as_posix(),
            "name": folder.name,
            **{k: engine[k] for k in ("summary", "origin", "contributor", "license", "features")},
            "source": engine["provenance"].get("source"),
            "added": added,
            "updated": updated,
            "pairs": [{"gpu": g, **model(m), "status": "measured", "result": r, "checkpoint": checkpoints[m]}
                      for (g, m), r in sorted(measured.items())]
                     + [{"gpu": g, **model(m), "status": "supported",
                         **({"checkpoint": checkpoints[m]} if m in checkpoints else {})} for g, m in supported],
        })
    return engines


def link(page, target):
    """A relative link from one browse/ page to a repository path."""
    return posixpath.relpath(target, posixpath.dirname(page))


def model_of(pair):
    """The Hugging Face model a pair belongs to: its checkpoint's root, or its own id unplaced."""
    return pair["hf"]["root"]["repository"] if pair.get("hf") else pair["model_name"]


def checkpoint_of(pair):
    return pair["checkpoint"]["repository"] if "checkpoint" in pair else pair["model"]


def tree(engines):
    """{gpu: {model: {checkpoint: [(engine, pair)]}}}, each level sorted; within a checkpoint
    measured engines first, then supported, each by name."""
    grown = {}
    for engine in engines:
        for pair in engine["pairs"]:
            grown.setdefault(pair["gpu"], {}).setdefault(model_of(pair), {}).setdefault(checkpoint_of(pair), []).append((engine, pair))
    order = lambda ep: (ep[1]["status"] != "measured", ep[0]["name"], ep[0]["path"])
    return {gpu: {model: {checkpoint: sorted(grown[gpu][model][checkpoint], key=order)
                          for checkpoint in sorted(grown[gpu][model], key=str.lower)}
                  for model in sorted(grown[gpu], key=str.lower)}
            for gpu in sorted(grown)}


def counts(found):
    return ", ".join(f"{n} {status}" for status in ("measured", "supported")
                     if (n := sum(p["status"] == status for _, p in found)))


def hugging_face(repository):
    return f"[`{repository}`](https://huggingface.co/{repository})"


def derivation(pair):
    """How a checkpoint derives from its model: "quantized", or "quantized from google/gemma-4-31B-it"
    when it derives from the model through another one."""
    hf = pair.get("hf")
    if not hf or not hf["lineage"]:
        return "the model itself" if hf else "–"
    relation = hf["relation"] or "derived"
    return relation if len(hf["lineage"]) == 1 else f"{relation} from `{hf['lineage'][0]['repository']}`"


def checkpoint_page(page, gpu, model, checkpoint, found):
    first = found[0][1]
    lines = [f"# {checkpoint} · {gpu}", "",
             f"[crit-hub]({link(page, 'README.md')}) › [browse]({link(page, 'browse/README.md')}) › "
             f"[{gpu}]({link(page, f'browse/{gpu}/README.md')}) › [{model}]({link(page, f'browse/{gpu}/{model}/README.md')}) › "
             f"{checkpoint}", ""]
    if first.get("hf"):
        lineage = first["hf"]["lineage"]
        steps = [f"{lineage[0]['relation'] or 'derived'} from {hugging_face(lineage[0]['repository'])}"] if lineage else ["the model itself"]
        steps += [f"a {step['relation'] or 'derivative'} of {hugging_face(step['repository'])}" for step in lineage[1:]]
        lines += [f"{hugging_face(checkpoint)} on Hugging Face: {', '.join(steps)}. Each engine's engine.json pins the "
                  "revision and, where it measured, the SHA-256 of every checkpoint file.", ""]
    lines += ["| Engine | Model id | Summary | Origin | Contributor | Decode | Prefill | First token | Context | Host RAM "
              "| Measured with | Status |",
              "| --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- |"]
    for engine, pair in found:
        result = pair.get("result", {})
        contributor = engine["contributor"]
        lines.append("| " + " | ".join([
            f"[{engine['name']}]({link(page, engine['path'])}/)",
            f"`{pair['model']}`",
            engine["summary"],
            "crit" if engine["origin"] == "crit" else "external, not reviewed",
            f"[{contributor['name']}]({contributor['repository']})",
            figure(result.get("decode_tok_s"), "tok/s"),
            figure(result.get("prefill_tok_s"), "tok/s"),
            ttft(result.get("ttft_ms")),
            f"{result['context_tokens']:,}" if "context_tokens" in result else "–",
            f"{result['host_ram_gib']} GiB" if "host_ram_gib" in result else "–",
            result.get("measured_with", "–"),
            pair["status"],
        ]) + " |")
    return HEADER + "\n".join(lines + ["", NOTE, ""])


def model_page(page, gpu, model, checkpoints):
    lines = [f"# {model} · {gpu}", "",
             f"[crit-hub]({link(page, 'README.md')}) › [browse]({link(page, 'browse/README.md')}) › "
             f"[{gpu}]({link(page, f'browse/{gpu}/README.md')}) › {model}", ""]
    first = next(iter(checkpoints.values()))[0][1]
    if first.get("hf"):
        lines += [f"{hugging_face(model)} on Hugging Face, by {first['hf']['root']['lab']['name']}.", ""]
    lines += ["| Checkpoint | Publisher | Relation | Bits | Size | Engines |", "| --- | --- | --- | ---: | ---: | --- |"]
    for checkpoint, found in checkpoints.items():
        hf = found[0][1].get("hf") or {}
        bits = (hf.get("quantization") or {}).get("bits")
        size = hf.get("size_bytes")
        lines.append("| " + " | ".join([
            f"[{checkpoint}]({link(page, f'browse/{gpu}/{model}/{checkpoint}/README.md')})",
            hf["publisher"]["name"] if hf else "–",
            derivation(found[0][1]),
            f"{bits}-bit" if bits else "–",
            f"{size / 1e9:.1f} GB" if size else "–",
            counts(found),
        ]) + " |")
    return HEADER + "\n".join(lines + [""])


def gpu_page(page, gpu, models):
    lines = [f"# {gpu}", "", f"[crit-hub]({link(page, 'README.md')}) › [browse]({link(page, 'browse/README.md')}) › {gpu}", "",
             "| Model | Lab | Checkpoints | Engines |", "| --- | --- | ---: | --- |"]
    for model, checkpoints in models.items():
        found = [ep for eps in checkpoints.values() for ep in eps]
        hf = found[0][1].get("hf")
        lab = hf["root"]["lab"]["name"] if hf else "–"
        lines.append(f"| [{model}]({link(page, f'browse/{gpu}/{model}/README.md')}) | {lab} | {len(checkpoints)} | {counts(found)} |")
    return HEADER + "\n".join(lines + [""])


def top_page(listed):
    lines = ["# Browse engines", "",
             "Pick your GPU, then the model, then its checkpoint: the Hugging Face repository an engine runs, "
             "such as a quantization or finetune of the model. Each checkpoint's page lists every engine that "
             "runs it and links its folder.", "",
             "| GPU | Models |", "| --- | ---: |"]
    lines += [f"| [{gpu}]({gpu}/README.md) | {len(models)} |" for gpu, models in listed.items()]
    lines += ["", "No engine for your GPU or model yet? Build one with [crit](https://github.com/crit-labs/crit) "
              "and [contribute](../README.md#contributing) it."]
    return HEADER + "\n".join(lines + [""])


def place(hub, engines, refresh):
    """Give every pair with a pinned checkpoint its "hf" block from browse/hf.json, resolving the
    checkpoints the cache lacks when refresh is set. Returns the cache, trimmed to pinned ones."""
    path = hub / CACHE
    cache = json.loads(path.read_text(encoding="utf-8")).get("checkpoints", {}) if path.is_file() else {}
    pinned = sorted({f"{p['checkpoint']['repository']}@{p['checkpoint']['revision']}"
                     for e in engines for p in e["pairs"] if "checkpoint" in p})
    names = {}
    for key in pinned:
        if refresh and key not in cache:
            repository, revision = key.rsplit("@", 1)
            print(f"resolving {repository} on Hugging Face")
            cache[key] = hf.resolve(repository, revision, names)
    for engine in engines:
        for pair in engine["pairs"]:
            checkpoint = pair.get("checkpoint")
            pair["hf"] = cache.get(f"{checkpoint['repository']}@{checkpoint['revision']}") if checkpoint else None
            pair["lab"] = pair["hf"]["root"]["lab"]["name"] if pair["hf"] else None
            pair["bits"] = (pair["hf"]["quantization"] or {}).get("bits") if pair["hf"] else None
    return {key: cache[key] for key in pinned if key in cache}


def build(hub, refresh=False):
    """Every file browse/ should hold, as {path: text}."""
    engines = load_engines(hub)
    cache = place(hub, engines, refresh)
    listed = tree(engines)
    files = {"browse/README.md": top_page(listed)}
    for gpu, models in listed.items():
        page = f"browse/{gpu}/README.md"
        files[page] = gpu_page(page, gpu, models)
        for model, checkpoints in models.items():
            page = f"browse/{gpu}/{model}/README.md"
            files[page] = model_page(page, gpu, model, checkpoints)
            for checkpoint, found in checkpoints.items():
                page = f"browse/{gpu}/{model}/{checkpoint}/README.md"
                files[page] = checkpoint_page(page, gpu, model, checkpoint, found)
    files["browse/index.json"] = json.dumps({"engines": engines}, indent=2, ensure_ascii=False) + "\n"
    files[CACHE] = json.dumps({"checkpoints": cache}, indent=2, ensure_ascii=False) + "\n"
    return files


def undated(path, text):
    """index.json without the engine dates, which --check does not compare."""
    if path != "browse/index.json":
        return text
    try:
        index = json.loads(text)
        for engine in index["engines"]:
            engine.pop("added", None)
            engine.pop("updated", None)
    except (ValueError, KeyError, TypeError, AttributeError):
        return text
    return index


def main(hub, check, refresh):
    hub = Path(hub).resolve()
    files = build(hub, refresh and not check)
    present = {p.relative_to(hub).as_posix() for p in (hub / "browse").rglob("*") if p.is_file()}
    stale = sorted(present - set(files))
    same = (lambda path, old, new: undated(path, old) == undated(path, new)) if check else (lambda path, old, new: old == new)
    changed = sorted(path for path, text in files.items()
                     if not (hub / path).is_file() or not same(path, (hub / path).read_text(encoding="utf-8"), text))
    if check:
        if stale or changed:
            raise SystemExit("browse/ is out of date; run python -B tools/build_index.py and commit it:\n  "
                             + "\n  ".join([f"changed {p}" for p in changed] + [f"stale   {p}" for p in stale]))
        print(f"browse/ is up to date ({len(files)} files)")
        return
    for path in stale:
        (hub / path).unlink()
    for path in changed:
        (hub / path).parent.mkdir(parents=True, exist_ok=True)
        (hub / path).write_text(files[path], encoding="utf-8", newline="\n")
    for folder in sorted((hub / "browse").rglob("*"), reverse=True):
        if folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    print(f"browse/: {len(changed)} written, {len(stale)} removed, {len(files)} files")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--hub", default=".", help="crit-hub checkout (default: the current folder)")
    p.add_argument("--check", action="store_true", help="fail if browse/ is out of date instead of writing it")
    p.add_argument("--refresh", action="store_true",
                   help="read Hugging Face for pinned checkpoints that browse/hf.json does not hold yet")
    args = p.parse_args()
    main(args.hub, args.check, args.refresh)
