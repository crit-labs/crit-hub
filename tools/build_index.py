"""Generate browse/, the GPU -> model -> quant -> engines index, from every engine's engine.json.

browse/README.md lists the GPUs, browse/<gpu>/README.md the models with engines on that GPU,
browse/<gpu>/<model>/README.md that model's quants on it, and browse/<gpu>/<model>/<quant>/README.md
every engine that runs that model id (<model>@<quant>): measured on it, or listed in a supports
group and not measured yet. browse/index.json carries each engine's card,
pinned source and pairs for the website and coding agents. Each pair keeps the model id
(qwen3.8-27b@NVFP4) and adds it split into model_name and quant, the model's lab and family from
models.json and the quant's bits and format from quants.json. When git history is available the
engine's dates as YYYY-MM-DD: "added", the commit that added its engine.json, and "updated", the
last commit that changed its folder (today while it has uncommitted changes); null without history,
as in a shallow clone. --check fails when browse/ is out of date instead of writing it; it ignores
the dates, which depend on the clone and on when a change is merged.
"""
import argparse
import json
import subprocess
from datetime import date
from pathlib import Path

HEADER = "<!-- Generated by tools/build_index.py from engines/*/*/engine.json; do not edit. -->\n\n"
NOTE = ("**Measured** figures are the headline numbers of the engine README's Measured section, on this GPU "
        "and checkpoint; **Measured with** says how. Figures from the same crit Eval protocol are comparable; "
        "any other method is the contributor's own report. **Supported** means the engine says it runs this "
        "pair and nobody has measured it here yet. Engines are listed, not ranked.")


def figure(value, unit):
    if value is None:
        return "–"
    if isinstance(value, list):
        return f"{value[0]:,}–{value[1]:,} {unit}"
    return f"{value:,} {unit}"


def ttft(value):
    if value is None:
        return "–"
    low, high = value if isinstance(value, list) else (value, value)
    if high < 1000:
        return figure(value, "ms")
    return figure([low / 1000, high / 1000] if low != high else low / 1000, "s")


def git(hub, *args):
    try:
        return subprocess.run(["git", "-C", str(hub), *args], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def dates(hub, folder):
    """When an engine was added and last updated, from git; None for both without full history."""
    if git(hub, "rev-parse", "--is-shallow-repository") != "false":
        return None, None
    path = folder.relative_to(hub).as_posix()
    today = date.today().isoformat()
    added = git(hub, "log", "--follow", "--diff-filter=A", "--format=%ad", "--date=short", "--", f"{path}/engine.json")
    updated = git(hub, "log", "-1", "--format=%ad", "--date=short", "--", path)
    if git(hub, "status", "--porcelain", "--", path):
        updated = today
    return (added.splitlines()[-1] if added else today), updated or today


def load_engines(hub):
    def table(name):
        path = hub / name
        return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}

    models, quants = table("models.json"), table("quants.json")

    def model(name):
        base, encoding = name.split("@")
        entry, quant = models.get(base, {}), quants.get(encoding, {})
        return {"model": name, "model_name": base, "quant": encoding, "lab": entry.get("lab"),
                "family": entry.get("family"), "bits": quant.get("bits"), "format": quant.get("format")}

    engines = []
    for folder in sorted(p for p in (hub / "engines").glob("*/*") if p.is_dir()):
        engine = json.loads((folder / "engine.json").read_text(encoding="utf-8"))
        measured = {(r["gpu"], r["model"]): r for r in engine["results"]}
        supported = sorted({(g, m) for group in engine.get("supports", []) for g in group["gpus"]
                            for m in group["models"]} - set(measured))
        checkpoints = {m: {k: c[k] for k in ("repository", "revision")} for m, c in engine["checkpoints"].items()}
        added, updated = dates(hub, folder)
        engines.append({
            "path": folder.relative_to(hub).as_posix(),
            "name": folder.name,
            **{k: engine[k] for k in ("summary", "origin", "contributor", "license", "features")},
            "source": engine["provenance"].get("source"),
            "added": added,
            "updated": updated,
            "pairs": [{"gpu": g, **model(m), "status": "measured", "result": r, "checkpoint": checkpoints[m]}
                      for (g, m), r in sorted(measured.items())]
                     + [{"gpu": g, **model(m), "status": "supported"} for g, m in supported],
        })
    return engines


def rows(engines, gpu, model):
    """The engines that run one pair: measured first, then supported, each by name."""
    found = [(e, p) for e in engines for p in e["pairs"] if (p["gpu"], p["model"]) == (gpu, model)]
    return sorted(found, key=lambda ep: (ep[1]["status"] != "measured", ep[0]["name"], ep[0]["path"]))


def pair_page(gpu, model, found):
    name, quant = model.split("@")
    checkpoints = sorted({p["checkpoint"]["repository"] for _, p in found if "checkpoint" in p})
    several = len(checkpoints) > 1
    lines = [f"# {model} · {gpu}", "",
             f"[crit-hub](../../../../README.md) › [browse](../../../README.md) › [{gpu}](../../README.md) › "
             f"[{name}](../README.md) › {quant}", ""]
    if checkpoints:
        links = " and ".join(f"[`{c}`](https://huggingface.co/{c})" for c in checkpoints)
        lines += [f"Measured on {links}. Each engine's engine.json pins the revision and the SHA-256 of every "
                  "checkpoint file.", ""]
    lines += ["| Engine | Summary | Origin | Contributor |" + (" Checkpoint |" if several else "")
              + " Decode | Prefill | First token | Context | Host RAM | Measured with | Status |",
              "| --- | --- | --- | --- |" + (" --- |" if several else "") + " ---: | ---: | ---: | ---: | ---: | --- | --- |"]
    for engine, pair in found:
        result = pair.get("result", {})
        contributor = engine["contributor"]
        checkpoint = [f"`{pair['checkpoint']['repository']}`" if "checkpoint" in pair else "–"] if several else []
        lines.append("| " + " | ".join([
            f"[{engine['name']}](../../../../{engine['path']}/)",
            engine["summary"],
            "crit" if engine["origin"] == "crit" else "external, not reviewed",
            f"[{contributor['name']}]({contributor['repository']})",
            *checkpoint,
            figure(result.get("decode_tok_s"), "tok/s"),
            figure(result.get("prefill_tok_s"), "tok/s"),
            ttft(result.get("ttft_ms")),
            f"{result['context_tokens']:,}" if "context_tokens" in result else "–",
            f"{result['host_ram_gib']} GiB" if "host_ram_gib" in result else "–",
            result.get("measured_with", "–"),
            pair["status"],
        ]) + " |")
    return HEADER + "\n".join(lines + ["", NOTE, ""])


def counts(found):
    return ", ".join(f"{n} {status}" for status in ("measured", "supported")
                     if (n := sum(p["status"] == status for _, p in found)))


def quants(models):
    """Model ids grouped by model name: {name: [ids]}, both sorted."""
    grouped = {}
    for model in models:
        grouped.setdefault(model.split("@")[0], []).append(model)
    return grouped


def gpu_page(gpu, models, engines):
    lines = [f"# {gpu}", "", f"[crit-hub](../../README.md) › [browse](../README.md) › {gpu}", "",
             "| Model | Lab | Quants | Engines |", "| --- | --- | ---: | --- |"]
    for name, ids in quants(models).items():
        found = [ep for model in ids for ep in rows(engines, gpu, model)]
        lab = found[0][1].get("lab") or "–"
        lines.append(f"| [{name}]({name}/README.md) | {lab} | {len(ids)} | {counts(found)} |")
    return HEADER + "\n".join(lines + [""])


def model_page(gpu, name, ids, engines):
    lines = [f"# {name} · {gpu}", "",
             f"[crit-hub](../../../README.md) › [browse](../../README.md) › [{gpu}](../README.md) › {name}", "",
             "| Quant | Bits | Format | Engines |", "| --- | ---: | --- | --- |"]
    for model in ids:
        quant = model.split("@")[1]
        found = rows(engines, gpu, model)
        pair = found[0][1]
        bits = f"{pair['bits']}-bit" if pair.get("bits") else "–"
        lines.append(f"| [{quant}]({quant}/README.md) | {bits} | {pair.get('format') or '–'} | {counts(found)} |")
    return HEADER + "\n".join(lines + [""])


def top_page(listed):
    lines = ["# Browse engines", "",
             "Pick your GPU, then your model, then its quant. Each quant's page lists every engine that runs "
             "that model and quant, built for exactly it or for a whole model family, and links its folder.", "",
             "| GPU | Models |", "| --- | ---: |"]
    lines += [f"| [{gpu}]({gpu}/README.md) | {len(quants(models))} |" for gpu, models in listed.items()]
    lines += ["", "No engine for your GPU or model yet? Build one with [crit](https://github.com/crit-labs/crit) "
              "and [contribute](../README.md#contributing) it."]
    return HEADER + "\n".join(lines + [""])


def build(hub):
    """Every file browse/ should hold, as {path: text}."""
    engines = load_engines(hub)
    listed = {}
    for gpu, model in sorted({(p["gpu"], p["model"]) for e in engines for p in e["pairs"]}):
        listed.setdefault(gpu, []).append(model)
    files = {"browse/README.md": top_page(listed)}
    for gpu, models in listed.items():
        files[f"browse/{gpu}/README.md"] = gpu_page(gpu, models, engines)
        for name, ids in quants(models).items():
            files[f"browse/{gpu}/{name}/README.md"] = model_page(gpu, name, ids, engines)
            for model in ids:
                files[f"browse/{gpu}/{name}/{model.split('@')[1]}/README.md"] = pair_page(gpu, model, rows(engines, gpu, model))
    files["browse/index.json"] = json.dumps({"engines": engines}, indent=2, ensure_ascii=False) + "\n"
    return files


def undated(path, text):
    """index.json without the engine dates, which --check does not compare."""
    if path != "browse/index.json":
        return text
    try:
        index = json.loads(text)
        for engine in index["engines"]:
            engine.pop("added", None)
            engine.pop("updated", None)
    except (ValueError, KeyError, TypeError, AttributeError):
        return text
    return index


def main(hub, check):
    hub = Path(hub).resolve()
    files = build(hub)
    present = {p.relative_to(hub).as_posix() for p in (hub / "browse").rglob("*") if p.is_file()}
    stale = sorted(present - set(files))
    same = (lambda path, old, new: undated(path, old) == undated(path, new)) if check else (lambda path, old, new: old == new)
    changed = sorted(path for path, text in files.items()
                     if not (hub / path).is_file() or not same(path, (hub / path).read_text(encoding="utf-8"), text))
    if check:
        if stale or changed:
            raise SystemExit("browse/ is out of date; run python -B tools/build_index.py and commit it:\n  "
                             + "\n  ".join([f"changed {p}" for p in changed] + [f"stale   {p}" for p in stale]))
        print(f"browse/ is up to date ({len(files)} files)")
        return
    for path in stale:
        (hub / path).unlink()
    for path in changed:
        (hub / path).parent.mkdir(parents=True, exist_ok=True)
        (hub / path).write_text(files[path], encoding="utf-8", newline="\n")
    for folder in sorted((hub / "browse").rglob("*"), reverse=True):
        if folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    print(f"browse/: {len(changed)} written, {len(stale)} removed, {len(files)} files")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--hub", default=".", help="crit-hub checkout (default: the current folder)")
    p.add_argument("--check", action="store_true", help="fail if browse/ is out of date instead of writing it")
    args = p.parse_args()
    main(args.hub, args.check)
